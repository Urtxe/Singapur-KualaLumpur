import { expect, test } from '@playwright/test'

const baseURL = 'http://127.0.0.1:4173/asia-trip/'

test.describe('Planificador y HOY', () => {
  test('crear una actividad solo pide el nombre y permite marcarla realizada', async ({ page }) => {
    await page.goto(`${baseURL}#agenda`)
    await page.getByRole('button', { name: 'Añadir actividad', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog.locator('[data-pl-form="activity"] details')).not.toHaveAttribute('open', '')
    await expect(dialog.getByLabel('Nombre')).toBeVisible()
    await expect(dialog.getByLabel('Lugar asociado (opcional)')).toBeVisible()
    await dialog.getByLabel('Nombre').fill('Pausa junto al río')
    await dialog.getByRole('button', { name: 'Guardar actividad' }).click()
    const activity = page.locator('.pl-activity').filter({ has: page.getByRole('heading', { name: 'Pausa junto al río' }) })
    await expect(activity).toBeVisible()
    await activity.getByRole('button', { name: 'Marcar realizada: Pausa junto al río' }).click()
    await expect(activity.locator('.pl-complete-lock')).toHaveText('Realizada')
    const details = activity.getByRole('button', { name: 'Ver Pausa junto al río' })
    await details.click()
    await page.getByText('Gestionar actividad', { exact: true }).click()
    await expect(dialog.getByRole('button', { name: 'Editar', exact: true })).toHaveCount(0)
    page.once('dialog', dialog => dialog.accept())
    await dialog.getByRole('button', { name: 'Marcar pendiente' }).click()
    await expect(activity.getByRole('button', { name: 'Marcar realizada: Pausa junto al río' })).toBeVisible()
    await expect(details).toBeFocused()
  })

  test('muestra la misma foto del lugar como miniatura y en la ficha de la actividad', async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 650 })
    await page.goto(`${baseURL}#agenda`)
    const day = page.getByLabel('Día de la agenda')
    await day.fill('2026-12-05')
    await day.dispatchEvent('change')

    const row = page.locator('.pl-activity[data-item="merlion-bay"]')
    const thumbnail = row.locator('img')
    await thumbnail.scrollIntoViewIfNeeded()
    await expect(thumbnail).toHaveAttribute('src', './places/merlion.webp')
    await expect.poll(() => thumbnail.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
    await expect(page.locator('.pl-activity[data-item="sg-breakfast-marina"] img')).toHaveCount(0)
    const thumbnailWidth = await thumbnail.evaluate(image => image.getBoundingClientRect().width)
    expect(thumbnailWidth).toBeLessThan(60)

    const opener = row.getByRole('button', { name: /^Ver / })
    await opener.click()
    const dialog = page.getByRole('dialog')
    const image = dialog.getByRole('img', { name: /Merlion/ })
    await expect(image).toHaveAttribute('src', './places/merlion.webp')
    await expect.poll(() => image.evaluate((photo: HTMLImageElement) => photo.naturalWidth)).toBeGreaterThan(0)
    expect(await image.evaluate(photo => photo.getBoundingClientRect().width)).toBeGreaterThan(thumbnailWidth * 3)
    await expect(dialog.getByRole('link', { name: 'Original' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
    await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click()
    await expect(opener).toBeFocused()
  })

  test('abre y cierra el formulario centrado sin desplazar el plan en un móvil compacto', async ({ page, isMobile }) => {
    test.skip(!isMobile, 'El formulario táctil se comprueba en los perfiles de móvil.')
    await page.setViewportSize({ width: 320, height: 568 })
    await page.goto(`${baseURL}#inicio`)
    await page.getByRole('link', { name: 'Planes', exact: true }).tap()
    const add = page.getByRole('button', { name: 'Añadir actividad', exact: true })
    const dialog = page.getByRole('dialog', { name: 'Nueva actividad' })
    await page.evaluate(() => window.scrollTo(0, 100))
    const before = await page.evaluate(() => window.scrollY)
    await add.tap()
    await expect(dialog.getByRole('button', { name: 'Cerrar', exact: true })).toBeFocused()
    await expect(dialog.getByLabel('Nombre')).toHaveCSS('font-size', '16px')
    await expect(dialog.getByRole('button', { name: 'Guardar actividad' })).toBeInViewport({ ratio: 1 })
    await dialog.getByText('Detalles avanzados', { exact: true }).tap()
    const size = await dialog.evaluate(element => {
      const { left, right, top, bottom } = element.getBoundingClientRect()
      return { left, right, top, bottom, width: innerWidth, height: innerHeight, horizontalScroll: element.scrollWidth - element.clientWidth }
    })
    expect(size.left).toBeGreaterThanOrEqual(10)
    expect(size.width - size.right).toBeCloseTo(size.left, 0)
    expect(size.top).toBeGreaterThanOrEqual(0)
    expect(size.bottom).toBeLessThanOrEqual(size.height)
    expect(size.horizontalScroll).toBeLessThanOrEqual(1)
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).tap()
    await expect(dialog).toBeHidden()
    await expect(add).toBeFocused()
    expect(await page.evaluate(() => window.scrollY)).toBe(before)

    await add.tap()
    await expect(dialog).toBeVisible()
    await page.goBack()
    await expect(page.getByRole('heading', { name: 'Hoy', exact: true })).toBeVisible()
    await expect(dialog).toBeHidden()
  })

  test('protege los vuelos confirmados frente a edición y reordenación', async ({ page }) => {
    await page.goto(`${baseURL}#agenda`)
    await page.getByLabel('Día de la agenda').fill('2026-12-04')
    await page.getByLabel('Día de la agenda').dispatchEvent('change')
    const flight = page.locator('.pl-activity[data-item="arrival-sin"]')
    await expect(flight).toBeVisible()
    await expect(flight).toHaveAttribute('draggable', 'false')
    await flight.getByRole('button', { name: 'Ver Llegada, inmigración y equipaje' }).click()
    const details = page.getByRole('dialog', { name: 'Llegada, inmigración y equipaje' })
    await expect(details.getByRole('button', { name: 'Editar', exact: true })).toHaveCount(0)
    await expect(details.locator('.pl-protected-note')).toContainText('está protegida')
  })

  test('permite alternar Plan A/B y editar una alternativa sin alterar Plan A', async ({ page }) => {
    await page.goto(`${baseURL}#agenda`)
    await page.getByLabel('Día de la agenda').fill('2026-12-05')
    await page.getByLabel('Día de la agenda').dispatchEvent('change')

    const original = page.locator('.pl-activity[data-item="merlion-bay"]')
    await expect(original).toBeVisible()
    await original.getByRole('button', { name: 'Ver Merlion Park', exact: true }).click()
    await page.getByText('Gestionar actividad', { exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Editar', exact: true }).click()
    const advanced = page.getByRole('dialog').locator('.pl-advanced')
    if ((await advanced.getAttribute('open')) === null) await advanced.locator('summary').click()
    await page.getByRole('dialog').locator('select[name="plan"]').selectOption('B')
    await page.getByRole('dialog').getByRole('button', { name: 'Guardar actividad' }).click()

    await expect(page.locator('.pl-activity[data-item="merlion-bay"]')).toHaveCount(0)
    await page.getByRole('button', { name: 'Plan B' }).click()
    const alternate = page.locator('.pl-activity[data-item="merlion-bay"]')
    await expect(alternate).toBeVisible()
    await expect(alternate.locator('.pl-plan-b')).toHaveText('PLAN B')
    await page.getByRole('button', { name: 'Activar Plan B' }).click()
    await expect(page.getByText('Activo', { exact: true })).toBeVisible()

    await alternate.getByRole('button', { name: 'Ver Merlion Park', exact: true }).click()
    await page.getByText('Gestionar actividad', { exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Editar', exact: true }).click()
    await page.getByRole('dialog').locator('[name="time"]').fill('10:10')
    await page.getByRole('dialog').getByRole('button', { name: 'Guardar actividad' }).click()
    await expect(page.locator('.pl-activity[data-item="merlion-bay"]')).toBeVisible()
    await page.getByRole('button', { name: 'Plan A' }).click()
    await expect(page.locator('.pl-activity[data-item="merlion-bay"]')).toHaveCount(0)
    await page.getByRole('button', { name: 'Activar Plan A' }).click()
    await expect(page.getByText('Activo', { exact: true })).toBeVisible()
  })

  test('admite reordenación táctil con pointer capture y muestra la vista cronológica por fecha', async ({ browser, browserName }) => {
    test.skip(browserName !== 'chromium', 'La secuencia de puntero real se verifica en Chromium.')
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true })
    const page = await context.newPage()
    const cdp = await context.newCDPSession(page)
    await page.goto(`${baseURL}#agenda`)
    await page.getByLabel('Día de la agenda').fill('2026-12-05')
    await page.getByLabel('Día de la agenda').dispatchEvent('change')

    const firstId = 'sg-breakfast-marina'
    const secondId = 'merlion-bay'
    const first = page.locator(`.pl-activity[data-item="${firstId}"]`)
    const second = page.locator(`.pl-activity[data-item="${secondId}"]`)
    await expect(first).toBeVisible()
    await expect(first.locator('[data-pl-action="grab"]')).toHaveCount(0)
    await page.getByRole('button', { name: 'Reordenar', exact: true }).tap()
    await first.evaluate(el => el.scrollIntoView({block:'start',behavior:'instant'}))
    const grip = first.locator('[data-pl-action="grab"]')
    await expect(grip).toBeInViewport()
    await expect(second).toBeInViewport()
    const gripBox = await grip.boundingBox()
    const secondBox = await second.boundingBox()
    if (!gripBox || !secondBox) throw new Error('No se pudo localizar la fila para reordenarla')
    const start = { x: gripBox.x + gripBox.width / 2, y: gripBox.y + gripBox.height / 2 }
    const end = { x: secondBox.x + Math.min(40, secondBox.width / 3), y: secondBox.y + Math.min(48,secondBox.height / 2) }
    expect(await page.evaluate(({x,y})=>!!document.elementFromPoint(x,y)?.closest('[data-pl-action="grab"]'),start)).toBe(true)
    const nextFrame = () => page.evaluate(()=>new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve()))))
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...start, id: 1 }] })
    await nextFrame()
    for (let step=1;step<=5;step++) {
      await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:start.x + (end.x-start.x)*step/5,y:start.y + (end.y-start.y)*step/5,id:1}]})
      await nextFrame()
    }
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(async () => page.locator('.pl-timeline .pl-activity').first().getAttribute('data-item')).toBe(secondId)
    await page.getByRole('button', { name: 'Terminar', exact: true }).tap()
    await expect(second.locator('[data-pl-action="grab"]')).toHaveCount(0)

    await page.getByText('Más herramientas para organizar el día', { exact: true }).click()
    await page.getByRole('button', { name: 'Cronología' }).click()
    const firstTime = await page.locator('.pl-activity').first().locator('.pl-time').innerText()
    expect(firstTime).toContain('08:00')
    await page.getByText('Más herramientas para organizar el día', { exact: true }).click()
    await page.getByRole('button', { name: 'Semana' }).click()
    await expect(page.locator('.pl-day-section')).toHaveCount(7)
    await context.close()
  })

  test('HOY usa la fecha local antes del viaje y permite previsualizar días del itinerario', async ({ page }) => {
    await page.clock.setFixedTime(new Date('2026-11-26T12:00:00+08:00'))
    await page.goto(`${baseURL}#inicio`)
    await expect(page.getByRole('heading', { name: 'Hoy' })).toBeVisible()
    const preview = page.getByLabel('Fecha de Hoy')
    await expect(preview).toHaveValue('2026-11-26')
    await expect(page.locator('.today-heading')).toContainText('26 de noviembre')
    await expect(page.locator('.today-heading')).toHaveAttribute('data-city', 'sg')
    await expect(page.getByText(/Faltan |El viaje empieza en/)).toHaveCount(1)
    await expect(page.getByRole('heading', { name: /El viaje empieza en/ })).toBeVisible()
    await expect(page.getByText(/Salida de Bilbao.*11:55/)).toBeVisible()
    await expect(page.getByRole('link', { name: 'Revisar preparativos' })).toBeVisible()
    await expect(page.locator('.today-wallet')).toHaveCount(0)
    await preview.selectOption('2026-12-05')
    await expect(page.locator('.today-heading')).toContainText('Singapur')
    await expect(page.locator('.today-heading small')).toHaveText('Vista previa')
    await expect(page.getByRole('heading', { name: 'Desayuno y traslado a Marina Bay' })).toBeVisible()
    await page.getByRole('button', { name: 'Volver a hoy' }).click()
    await expect(preview).toHaveValue('2026-11-26')
    await expect(page.getByRole('heading', { name: /El viaje empieza en/ })).toBeVisible()
  })

  test('Planes abre por defecto el primer día del viaje antes de la salida', async ({ page }) => {
    await page.clock.setFixedTime(new Date('2026-11-26T12:00:00+08:00'))
    await page.goto(`${baseURL}#agenda`)
    await expect(page.getByLabel('Día de la agenda')).toHaveValue('2026-12-03')
    await expect(page.locator('.pl-activity[data-item="bio-ams"]')).toBeVisible()
  })
})
